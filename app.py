APP_TITLE = "Boolean Expression Optimizer & Circuit Simulator Pro"
VARIABLE_NAMES = list("ABCDEF")
TRANSFORMS = standard_transformations + (convert_xor,)

def parse_boolean_expression(expression):
    expression = (expression or "").strip()
    if not expression:
        raise ValueError("Enter a Boolean expression first.")
    # Keep this intentionally small and safe: only A-F, Boolean operators, constants and parentheses.
    if not re.fullmatch(r"[A-Fa-f01\s&|~()]+", expression):
        raise ValueError("Use only variables A–F, constants 0/1, operators &, |, ~, and parentheses.")
    names = sorted(set(re.findall(r"[A-Fa-f]", expression.upper())))
    local = {name: sp.Symbol(name) for name in VARIABLE_NAMES}
    normalized = expression.upper()
    try:
        original = parse_expr(normalized, local_dict=local, transformations=TRANSFORMS, evaluate=False)
    except Exception as exc:
        raise ValueError("Could not parse that expression. Check the operators and parentheses.") from exc
    if not isinstance(original, (sp.Symbol, sp.Not, sp.And, sp.Or, sp.true.__class__, sp.false.__class__)):
        raise ValueError("Expression must be built from Boolean variables, AND (&), OR (|), NOT (~), and parentheses.")
    # Reject any unexpected symbols or operations.
    if any(str(s) not in VARIABLE_NAMES for s in original.free_symbols):
        raise ValueError("Use variables A–F only.")
    return normalized, original, names

def bool_value(expr, assignment):
    value = expr.subs(assignment)
    return int(bool(value))

def make_truth_table(original, simplified, variables):
    rows = []
    for bits in product([0, 1], repeat=len(variables)):
        assignment = {sp.Symbol(v): bool(bit) for v, bit in zip(variables, bits)}
        ov = bool_value(original, assignment)
        sv = bool_value(simplified, assignment)
        row = {v: bit for v, bit in zip(variables, bits)}
        row.update({"Original F": ov, "Optimized F": sv})
        rows.append(row)
    return pd.DataFrame(rows)

def verilog_expr(expr):
    if expr is sp.true or expr == sp.true:
        return "1'b1"
    if expr is sp.false or expr == sp.false:
        return "1'b0"
    if isinstance(expr, sp.Symbol):
        return str(expr)
    if isinstance(expr, sp.Not):
        return f"~({verilog_expr(expr.args[0])})"
    if isinstance(expr, sp.And):
        return "(" + " & ".join(verilog_expr(a) for a in expr.args) + ")"
    if isinstance(expr, sp.Or):
        return "(" + " | ".join(verilog_expr(a) for a in expr.args) + ")"
    raise ValueError(f"Unsupported Boolean expression node: {expr}")


def make_verilog(original, simplified, variables):
    ports = ", ".join(variables + ["F"])

    if variables:
        inputs = f"    input {', '.join(variables)};\n"
    else:
        inputs = ""

    return (
        "// Generated by Boolean Expression Optimizer & Circuit Simulator Pro\n"
        f"module original_circuit({ports});\n"
        f"{inputs}"
        "    output F;\n"
        f"    assign F = {verilog_expr(original)};\n"
        "endmodule\n\n"
        f"module optimized_circuit({ports});\n"
        f"{inputs}"
        "    output F;\n"
        f"    assign F = {verilog_expr(simplified)};\n"
        "endmodule\n"
    )

def make_testbench(variables):
    if not variables:
        return "`timescale 1ns/1ps\nmodule testbench;\n  wire original_F, optimized_F;\n  original_circuit a(.F(original_F));\n  optimized_circuit b(.F(optimized_F));\n  initial begin #1; $display(\"Original=%b Optimized=%b\", original_F, optimized_F); $finish; end\nendmodule\n"
    declarations = "\n".join(f"    reg {v};" for v in variables)
    ports = ", ".join(f".{v}({v})" for v in variables)
    assign_lines = "\n".join(f"            {v} = (i >> {len(variables)-idx-1}) & 1;" for idx, v in enumerate(variables))
    packed = "{" + ", ".join(variables) + "}"
    count = 2 ** len(variables)
    return f"""`timescale 1ns/1ps
module testbench;
{declarations}
    wire original_F;
    wire optimized_F;
    integer i;
    original_circuit original_dut({ports}, .F(original_F));
    optimized_circuit optimized_dut({ports}, .F(optimized_F));
    initial begin
        $display("Test | Inputs | Original | Optimized | Result");
        for (i = 0; i < {count}; i = i + 1) begin
{assign_lines}
            #1;
            if (original_F === optimized_F)
                $display("%0d | %b | %b | %b | PASS", i, {packed}, original_F, optimized_F);
            else
                $display("%0d | %b | %b | %b | FAIL", i, {packed}, original_F, optimized_F);
        end
        $finish;
    end
endmodule
"""


def kmap_html(table, variables, simplified=None):
    n = len(variables)

    if n == 0:
        value = int(table.iloc[0]["Original F"])
        return f"""
        <div class="kmap-wrap">
            <h3>Constant Boolean Function</h3>
            <p><b>Final simplified output:</b> F = {value}</p>
            <p>The output is always {value}; no variables are needed.</p>
        </div>
        """

    if n > 4:
        result = str(simplified) if simplified is not None else "See optimized expression above"
        return f"""
        <div class="kmap-wrap">
            <h3>Karnaugh Map</h3>
            <p>K-map display supports up to 4 variables.</p>
            <p><b>Final simplified expression:</b> F = {result}</p>
            <p>Use the truth table for functions with 5 or 6 variables.</p>
        </div>
        """

    def gray(nbits):
        return [format(i ^ (i >> 1), f"0{nbits}b")
                for i in range(2 ** nbits)]

    if n == 1:
        v = variables[0]
        lookup = {
            int(row[v]): int(row["Original F"])
            for _, row in table.iterrows()
        }
        cells = "".join(
            f"<td class='{'one' if lookup[i] else 'zero'}'>{lookup[i]}</td>"
            for i in (0, 1)
        )
        result = str(simplified) if simplified is not None else "See optimized expression above"
        return f"""
        <div class="kmap-wrap">
            <h3>1-variable Karnaugh Map</h3>
            <table class="kmap">
                <tr><th>{v}</th><th>0</th><th>1</th></tr>
                <tr><th>F</th>{cells}</tr>
            </table>
            <p><b>Final simplified expression:</b> F = {result}</p>
        </div>
        """

    row_vars = variables[:n // 2]
    col_vars = variables[n // 2:]
    row_codes = gray(len(row_vars))
    col_codes = gray(len(col_vars))

    lookup = {}
    for _, row in table.iterrows():
        key = "".join(str(int(row[v])) for v in variables)
        lookup[key] = int(row["Original F"])

    header = "".join(f"<th>{code}</th>" for code in col_codes)
    body = ""

    for rc in row_codes:
        body += f"<tr><th>{rc}</th>"
        for cc in col_codes:
            value = lookup[rc + cc]
            cell_class = "one" if value else "zero"
            body += f"<td class='{cell_class}'>{value}</td>"
        body += "</tr>"

    result = str(simplified) if simplified is not None else "See optimized expression above"

    return f"""
    <div class="kmap-wrap">
        <h3>{n}-variable Karnaugh Map</h3>
        <p>Rows: {', '.join(row_vars)} · Columns: {', '.join(col_vars)}</p>
        <table class="kmap">
            <tr><th>{'/'.join(row_vars)} / {'/'.join(col_vars)}</th>{header}</tr>
            {body}
        </table>
        <p><b>Final simplified expression:</b> F = {result}</p>
        <p class="note">Green cells represent output 1; other cells represent output 0.</p>
    </div>
    """
    
def svg_circuit(expr, title):
    """Draw a labeled Boolean logic circuit using SVG."""

    def is_leaf(node):
        return (
            isinstance(node, sp.Symbol)
            or node == sp.true
            or node == sp.false
        )

    def leaves(node):
        if is_leaf(node):
            return [node]
        result = []
        for child in node.args:
            result.extend(leaves(child))
        return result

    leaf_nodes = leaves(expr)
    leaf_count = len(leaf_nodes)
    max_depth = 0

    def get_depth(node):
        if is_leaf(node):
            return 0
        return 1 + max(get_depth(child) for child in node.args)

    max_depth = get_depth(expr)
    width = max(650, 190 * (max_depth + 1) + 180)
    height = max(190, 65 * leaf_count + 70)

    left = 140
    right = width - 100
    x_step = (right - left) / max(1, max_depth + 1)

    elements = []
    wires = []
    leaf_index = [0]

    def draw(node, level=0):
        if is_leaf(node):
            y = 45 + leaf_index[0] * 65
            leaf_index[0] += 1
            x = left

            if isinstance(node, sp.Symbol):
                label = str(node)
            elif node == sp.true:
                label = "1"
            else:
                label = "0"

            elements.append(
                f"<text x='{x-12}' y='{y+5}' "
                f"text-anchor='end' class='label'>{label}</text>"
                f"<circle cx='{x}' cy='{y}' r='3' class='dot'/>"
            )
            return (x, y)

        child_positions = [
            draw(child, level + 1) for child in node.args
        ]

        y = sum(p[1] for p in child_positions) / len(child_positions)
        x = right - level * x_step
        gate_w = 64
        gate_h = max(42, 24 * len(child_positions))
        top = y - gate_h / 2
        gx1 = x - gate_w / 2
        gx2 = x + gate_w / 2

        if isinstance(node, sp.Not):
            path = (
                f"M {gx1} {top} "
                f"L {gx2-9} {y} "
                f"L {gx1} {top+gate_h} Z"
            )
            elements.append(
                f"<path d='{path}' class='gate'/>"
                f"<circle cx='{gx2-4}' cy='{y}' r='4' class='bubble'/>"
            )
            input_points = [(gx1, y)]
            output_x = gx2 + 1

        elif isinstance(node, sp.And):
            path = (
                f"M {gx1} {top} "
                f"L {x} {top} "
                f"A {gate_w/2} {gate_h/2} 0 0 1 {x} {top+gate_h} "
                f"L {gx1} {top+gate_h} Z"
            )
            elements.append(
                f"<path d='{path}' class='gate'/>"
                f"<text x='{x-5}' y='{y+4}' "
                f"class='gate-label'>AND</text>"
            )
            input_points = [
                (gx1, top + gate_h * (i+1) / (len(child_positions)+1))
                for i in range(len(child_positions))
            ]
            output_x = gx2

        elif isinstance(node, sp.Or):
            path = (
                f"M {gx1} {top} "
                f"Q {gx1+18} {y} {gx1} {top+gate_h} "
                f"Q {x+12} {top+gate_h} {gx2} {y} "
                f"Q {x+12} {top} {gx1} {top} Z"
            )
            elements.append(
                f"<path d='{path}' class='gate'/>"
                f"<text x='{x-7}' y='{y+4}' "
                f"class='gate-label'>OR</text>"
            )
            input_points = [
                (gx1+5, top + gate_h * (i+1) / (len(child_positions)+1))
                for i in range(len(child_positions))
            ]
            output_x = gx2

        else:
            gate_name = type(node).__name__.upper()
            elements.append(
                f"<rect x='{gx1}' y='{top}' width='{gate_w}' "
                f"height='{gate_h}' rx='5' class='gate'/>"
                f"<text x='{x}' y='{y+4}' text-anchor='middle' "
                f"class='gate-label'>{gate_name}</text>"
            )
            input_points = [
                (gx1, top + gate_h * (i+1) / (len(child_positions)+1))
                for i in range(len(child_positions))
            ]
            output_x = gx2

        for (cx, cy), (ix, iy) in zip(child_positions, input_points):
            mid_x = (cx + ix) / 2
            wires.append(
                f"<path d='M {cx} {cy} H {mid_x} V {iy} H {ix}' "
                f"class='wire'/>"
            )

        return (output_x, y)

    output_x, output_y = draw(expr)
    output_end = width - 35

    wires.append(
        f"<path d='M {output_x} {output_y} H {output_end-22}' "
        f"class='wire'/>"
    )
    elements.append(
        f"<text x='{output_end}' y='{output_y+5}' "
        f"text-anchor='end' class='label'>F</text>"
    )

    return f"""
    <div class="circuit-card">
      <h3>{title}</h3>
      <svg xmlns="http://www.w3.org/2000/svg"
           viewBox="0 0 {width} {height}"
           role="img" aria-label="{title}"
           style="display:block;width:100%;height:auto">
        <style>
          .wire {{ stroke:#334155; stroke-width:2; fill:none;
                   stroke-linejoin:round; stroke-linecap:round; }}
          .gate {{ stroke:#2563eb; stroke-width:2; fill:#eff6ff; }}
          .bubble {{ stroke:#2563eb; stroke-width:2; fill:white; }}
          .dot {{ fill:#334155; }}
          .label {{ font:bold 15px sans-serif; fill:#0f172a; }}
          .gate-label {{ font:bold 9px sans-serif; fill:#1d4ed8; }}
        </style>
        {''.join(wires)}
        {''.join(elements)}
      </svg>
    </div>
    """

def make_circuits(original, simplified):
    return "<div class='circuits'>" + svg_circuit(original, "Original circuit") + svg_circuit(simplified, "Optimized circuit") + "</div>"

def make_waveform(table, variables):
    if table.empty:
        return None
    labels = []
    for _, row in table.iterrows():
        labels.append("".join(str(int(row[v])) for v in variables) if variables else "constant")
    x = list(range(len(table)))
    fig, ax = plt.subplots(figsize=(max(7, len(x)*0.42), 3.8))
    series = [
        ("Original F", 2.5),
        ("Optimized F", 1.2),
    ]
    for name, yoffset in series:
        vals = table[name].astype(int).tolist()
        ax.step(x, [v + yoffset for v in vals], where="post", linewidth=2, label=name)
    ax.set_yticks([0.5, 1.5, 2.5, 3.5], ["0", "1", "0", "1"])
    ax.set_ylim(0, 4.1)
    ax.set_xticks(x, labels, rotation=0 if len(x) <= 8 else 90)
    ax.set_xlabel("Input combination")
    ax.set_title("Output comparison across truth-table input combinations")
    ax.grid(True, axis="x", alpha=0.25)
    ax.legend(loc="upper right")
    fig.tight_layout()
    return fig

def simulate_verilog(verilog, testbench):
    if not shutil_which("iverilog"):
        return "Icarus Verilog is not installed in this environment. Boolean equivalence was checked using the truth table."
    with tempfile.TemporaryDirectory() as td:
        src = os.path.join(td, "circuits.v")
        tb = os.path.join(td, "testbench.v")
        out = os.path.join(td, "simulation.out")
        open(src, "w", encoding="utf-8").write(verilog)
        open(tb, "w", encoding="utf-8").write(testbench)
        compile_result = subprocess.run(["iverilog", "-o", out, src, tb], capture_output=True, text=True, timeout=20)
        if compile_result.returncode:
            return "Compilation failed:\n" + compile_result.stderr
        run_result = subprocess.run(["vvp", out], capture_output=True, text=True, timeout=20)
        return (run_result.stdout or "") + (run_result.stderr or "")

def shutil_which(cmd):
    import shutil
    return shutil.which(cmd)

def run_optimizer(expression):
    try:
        normalized, original, variables = parse_boolean_expression(expression)
        simplified = sp.simplify_logic(original, form="dnf", force=True)
        # Sympy may return a BooleanTrue/False constant.
        table = make_truth_table(original, simplified, variables)
        if not (table["Original F"] == table["Optimized F"]).all():
            equivalence = "FAIL"
        else:
            equivalence = "PASS"
        verilog = make_verilog(original, simplified, variables)
        tb = make_testbench(variables)
        sim = simulate_verilog(verilog, tb)
        kmap = kmap_html(table, variables, simplified)
        circuits = make_circuits(original, simplified)
        waveform = make_waveform(table, variables)
        status = f"**Boolean equivalence: {equivalence}**\n\nVariables detected: {', '.join(variables) if variables else 'none'} · Truth-table rows: {len(table)}"
        return normalized, str(simplified), status, table, kmap, circuits, waveform, verilog, tb, sim
    except Exception as exc:
        msg = f"Could not process expression: {exc}"
        return "", "", msg, pd.DataFrame(), "<div class='note'>K-map unavailable until a valid expression is entered.</div>", "<div class='note'>Circuit diagram unavailable until a valid expression is entered.</div>", None, "", "", ""

